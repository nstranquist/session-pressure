package sessionpressure

import "time"

// browserProcess retains no command lines. StartIdentity binds native discovery
// to the same kernel birth that enforcement revalidates before each signal.
type browserProcess struct {
	PID           int
	StartedAt     time.Time
	StartIdentity string
	// UserDataDir is the root's --user-data-dir. It locates a snapref session
	// record and is never logged.
	UserDataDir string
}
